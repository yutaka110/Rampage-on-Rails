"""Bake the optical hulls used by the cavern crystal pixel shader."""

from collections import defaultdict
from itertools import combinations
from math import sqrt
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MESHES = ROOT / "Resources/course_meshes"
OUTPUT = ROOT / "Resources/CrystalOpticalHulls.hlsli"
BRANCH_MARKER = "# UV.x integer part selects the optical shard; UV.y retains the original height."


def subtract(a, b):
    return tuple(x - y for x, y in zip(a, b))


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def cross(a, b):
    return (a[1]*b[2] - a[2]*b[1], a[2]*b[0] - a[0]*b[2], a[0]*b[1] - a[1]*b[0])


def mesh_shards(path, encode_branches=False):
    lines = path.read_text(encoding="ascii").splitlines()
    positions = []
    uv_lines = []
    faces = []
    for index, line in enumerate(lines):
        fields = line.split()
        if line.startswith("v "):
            x, y, z = map(float, fields[1:])
            positions.append((x, y, -z))  # Assimp converts OBJ positions to left handed space.
        elif line.startswith("vt "):
            uv_lines.append(index)
        elif line.startswith("f "):
            faces.append([tuple(int(value)-1 for value in vertex.split("/")[:2]) for vertex in fields[1:]])

    neighbors = defaultdict(set)
    for face in faces:
        ids = {vertex for vertex, _ in face}
        for vertex in ids:
            neighbors[vertex].update(ids - {vertex})
    shards = []
    shard_ids = {}
    for first in range(len(positions)):
        if first in shard_ids:
            continue
        branch = len(shards)
        shard = []
        pending = [first]
        shard_ids[first] = branch
        while pending:
            vertex = pending.pop()
            shard.append(positions[vertex])
            for neighbor in sorted(neighbors[vertex]):
                if neighbor in shard_ids:
                    continue
                shard_ids[neighbor] = branch
                pending.append(neighbor)
        shards.append(shard)

    unencoded = encode_branches and BRANCH_MARKER not in lines
    uv_owners = {}
    for face in faces:
        for vertex, uv_index in face:
            branch = shard_ids[vertex]
            previous_owner = uv_owners.setdefault(uv_index, branch)
            if previous_owner != branch:
                raise ValueError(f"{path.name}: optical shards share a UV vertex")
    for uv_index, branch in uv_owners.items():
        index = uv_lines[uv_index]
        _, u, v = lines[index].split()
        if unencoded:
            lines[index] = f"vt {branch + .0625 + .875 * float(u):.6f} {v}"
        elif int(float(u)) != branch:
            raise ValueError(f"{path.name}: UV shard id differs from the connected surface")
    if unencoded:
        lines.insert(1, BRANCH_MARKER)
        path.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    return shards


def hull_planes(points):
    planes = []
    for a, b, c in combinations(points, 3):
        normal = cross(subtract(b, a), subtract(c, a))
        length = sqrt(dot(normal, normal))
        if length < 1e-7:
            continue
        normal = tuple(value / length for value in normal)
        projections = [dot(normal, point) for point in points]
        anchor = dot(normal, a)
        limit = max(projections)
        if limit - anchor > 1e-6:
            low = min(projections)
            if anchor - low > 1e-6:
                continue
            normal = tuple(-value for value in normal)
            limit = -low
        # Coplanar faces can enumerate the same support plane more than once.
        if any(dot(normal, plane[:3]) > .999999 and abs(limit-plane[3]) < .00001 for plane in planes):
            continue
        planes.append((*normal, limit))
    if len(planes) < 4:
        raise ValueError("Optical shard is not a closed volume")
    return planes


def main():
    ordinary = mesh_shards(MESHES / "CrystalCavernCluster/CrystalCavernCluster.obj", encode_branches=True)
    landmark = mesh_shards(MESHES / "CrystalCavernLandmark/CrystalCavernLandmark.obj")
    hulls = [hull_planes(points) for points in ordinary + landmark]
    offset = 0
    ranges = []
    for planes in hulls:
        ranges.append(f"    uint2({offset}, {len(planes)}),")
        offset += len(planes)

    lines = [
        "#ifndef GE3_CRYSTAL_OPTICAL_HULLS", "#define GE3_CRYSTAL_OPTICAL_HULLS", "",
        "// Generated by tools/generate_crystal_optical_hulls.py from the crystal mesh positions.",
        f"static const uint CrystalClusterShardCount = {len(ordinary)};",
        f"static const uint CrystalLandmarkShardCount = {len(landmark)};", "",
        f"static const uint2 CrystalHullRanges[{len(hulls)}] = {{", *ranges, "};", "",
        f"static const float4 CrystalHullPlanes[{offset}] = {{",
    ]
    for index, planes in enumerate(hulls):
        lines.append(f"    // Shard {index}")
        lines.extend("    float4(" + ", ".join(f"{value:.6f}f" for value in plane) + ")," for plane in planes)
    lines.extend(["};", "", "#endif", ""])
    generated = "\n".join(lines)
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="ascii") != generated:
        OUTPUT.write_text(generated, encoding="ascii", newline="\n")
    print(f"Baked {len(hulls)} optical hulls with {offset} support planes, max {max(map(len, hulls))} per shard.")


if __name__ == "__main__":
    main()
